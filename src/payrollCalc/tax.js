function isR8TaxMonth(yearMonth) {
  const [year] = yearMonth.split("-").map(Number);
  return year >= 2026;
}

export function calcWithholdingTax(taxableAmount, dependents, yearMonth) {
  const dep = Math.min(Math.max(0, Math.floor(dependents)), 7);
  if (yearMonth && isR8TaxMonth(yearMonth)) {
    if (taxableAmount < 105000) return 0;
    const row = WITHHOLDING_TABLE_R8.find(r => taxableAmount >= r.min && taxableAmount < r.max);
    if (row) return row.tax[dep];
    const seg = WITHHOLDING_TABLE_R8_OVER_740000.find(s => taxableAmount >= s.from && taxableAmount < s.to);
    if (!seg) return 0; // 3,500,000円以上は月額表の対象外（未対応）
    return seg.base[dep] + Math.floor((taxableAmount - seg.from) * seg.rate);
  }
  if (taxableAmount < 88000) return 0;
  const row = WITHHOLDING_TABLE_R7.find(r => taxableAmount >= r.min && taxableAmount < r.max);
  if (!row) return 0;
  return row.tax[dep];
}

// 賞与の源泉徴収税計算（前月の給与額と扶養人数から概算）
export function calculateBonusIncomeTax(
  bonusAfterInsurance,
  prevMonthlySalaryAfterInsurance,
  dependents
) {
  if (bonusAfterInsurance <= 0) return 0;
  const prevTax = calcWithholdingTax(prevMonthlySalaryAfterInsurance, dependents);
  const rate = prevMonthlySalaryAfterInsurance > 0
    ? prevTax / prevMonthlySalaryAfterInsurance
    : 0;
  return Math.floor(bonusAfterInsurance * rate);
}